def build_channel() -> str:
    """'dev' for a source checkout or wheel; a packaged build writes core._build_info (a runtime hook, not a file)
    with CHANNEL = 'public' (or 'beta') at build time, so the value cannot be switched by a file next to the app."""
    try:
        from core import _build_info  # generated by packaging only; absent from the repository
    except ImportError:
        return "dev"
    channel = getattr(_build_info, "CHANNEL", "dev")
    return channel if channel in ("dev", "beta", "public") else "dev"


IS_DEV_BUILD = build_channel() == "dev"


def gateway_profile_locked() -> bool:
    """P10 (rule "공개 빌드는 commercial 프로필 고정", GATEWAY_DESIGN.md section 2): True when build info fixes the
    gateway profile to "commercial" whatever else says: CHANNEL "public", or a CHANNEL this code does not know (fails
    closed; for .env build_channel() still calls that "dev"). Read at call time, like build_channel();
    core/gateway profile() checks it before its test override."""
    try:
        from core import _build_info  # written by packaging/rthook_build_info.py.in only
    except ImportError:
        return False
    return getattr(_build_info, "CHANNEL", "dev") not in ("dev", "beta")


def gateway_profile() -> str:
    """The data gateway profile from build info, read like build_channel(): field GATEWAY_PROFILE ("personal" or
    "commercial"). No build info, or no such field: "personal". A locked build (public): "commercial" whatever the
    field says. Any other value fails closed to "commercial", never "personal"."""
    if gateway_profile_locked():
        return "commercial"
    try:
        from core import _build_info
    except ImportError:
        return "personal"
    chosen = getattr(_build_info, "GATEWAY_PROFILE", "personal")
    return chosen if chosen in GATEWAY_PROFILES else "commercial"


GATEWAY_PROFILE = gateway_profile()     # resolved once at import, like IS_DEV_BUILD (what a build's selfcheck records)


def may_read_dotenv() -> bool:
    """D7-G rule 3: a public build never reads .env; only a development build may."""
    return IS_DEV_BUILD


def is_configured(*values: str) -> bool:
    return all(isinstance(v, str) and v.strip() for v in values)


def company_data_server_configured() -> bool:
    """True only when the commercial profile is chosen and the company data server address is set."""
    return GATEWAY_PROFILE == "commercial" and is_configured(DATA_API_BASE)


def accounts_configured() -> bool:
    return is_configured(COGNITO_REGION, COGNITO_USER_POOL_ID, COGNITO_DESKTOP_CLIENT_ID)
