# display right (yahoo, fmp, gs_marquee) are off. GATEWAY_PROFILE is resolved from build info below (P10):
# a public build is always "commercial"; a source checkout or wheel is "personal".
GATEWAY_PROFILES = ("personal", "commercial")
DATA_API_BASE = ""              # company data server; empty until it exists, so the company route stays off


def build_channel() -> str:
    """'dev' for a source checkout or wheel; a packaged build writes core._build_info (a runtime hook, not a file)
    with CHANNEL = 'public' (or 'beta') at build time, so the value cannot be switched by a file next to the app."""
    try:
        from core import _build_info  # generated by packaging only; absent from the repository
    except ImportError:
        return "dev"
    channel = getattr(_build_info, "CHANNEL", "dev")
    return channel if channel in ("dev", "beta", "public") else "dev"


IS_DEV_BUILD = build_channel() == "dev"


def gateway_profile_locked() -> bool:
    """P10 (rule "공개 빌드는 commercial 프로필 고정", GATEWAY_DESIGN.md section 2): True when the gateway profile is fixed
    to "commercial" whatever else says. Build info present: unless its CHANNEL is "dev" or "beta" (so "public", a value
    this code does not know, or no CHANNEL at all: fails closed; for .env build_channel() still calls the last two
    "dev"). No build info: only in a PyInstaller bundle (sys.frozen and sys._MEIPASS), whose runtime hook did not run.
    Read at call time from sys.modules, with no import: packaging/rthook_build_info.py.in only ever puts build info
    there, and a core/_build_info.py file is already there from build_channel() at import, so a source run pays no
    failing import on each core/gateway profile() call (which checks this before its test override)."""
    info = sys.modules.get("core._build_info")
    if info is None:
        return bool(getattr(sys, "frozen", False) and getattr(sys, "_MEIPASS", None))
    return getattr(info, "CHANNEL", None) not in ("dev", "beta")


def gateway_profile() -> str:
    """The data gateway profile from build info, read like build_channel(): field GATEWAY_PROFILE ("personal" or
    "commercial"). No build info (a source checkout or wheel), or CHANNEL "dev"/"beta" without the field: "personal".
    A locked build (gateway_profile_locked: public, no or unknown CHANNEL, a bundle without build info): "commercial"
    whatever the field says. Any other value fails closed to "commercial", never "personal"."""
    if gateway_profile_locked():
        return "commercial"
    try:
        from core import _build_info
    except ImportError:
        return "personal"
    chosen = getattr(_build_info, "GATEWAY_PROFILE", "personal")
    return chosen if chosen in GATEWAY_PROFILES else "commercial"


GATEWAY_PROFILE = gateway_profile()     # resolved once at import, like IS_DEV_BUILD (what a build's selfcheck records)


def may_read_dotenv() -> bool:
    """D7-G rule 3: a public build never reads .env; only a development build may."""
    return IS_DEV_BUILD


def is_configured(*values: str) -> bool:
    return all(isinstance(v, str) and v.strip() for v in values)


def company_data_server_configured() -> bool:
    """True only when the commercial profile is chosen and the company data server address is set."""
    return GATEWAY_PROFILE == "commercial" and is_configured(DATA_API_BASE)


def accounts_configured() -> bool:
    return is_configured(COGNITO_REGION, COGNITO_USER_POOL_ID, COGNITO_DESKTOP_CLIENT_ID)
