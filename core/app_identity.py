def build_channel() -> str:
    """'dev' for a source checkout or wheel; a packaged build writes core/_build_info.py with
    CHANNEL = 'public' (or 'beta') at build time, so the value cannot be switched by a file next to the app."""
    try:
        from core import _build_info  # generated by packaging only; absent from the repository
    except ImportError:
        return "dev"
    channel = getattr(_build_info, "CHANNEL", "dev")
    return channel if channel in ("dev", "beta", "public") else "dev"


IS_DEV_BUILD = build_channel() == "dev"


def may_read_dotenv() -> bool:
    """D7-G rule 3: a public build never reads .env; only a development build may."""
    return IS_DEV_BUILD


def is_configured(*values: str) -> bool:
    return all(isinstance(v, str) and v.strip() for v in values)


def accounts_configured() -> bool:
    return is_configured(COGNITO_REGION, COGNITO_USER_POOL_ID, COGNITO_DESKTOP_CLIENT_ID)
