"""Export the DIDM contracts as JSON Schema files (DIDM-2).

    python -B -m tools.didm.export_schema            # write docs/didm/schema/*.schema.json
    python -B -m tools.didm.export_schema --check    # exit 0 only if the files match the code

The Python validators stay the authority (core/didm/llm/schema.py ``validate_record``,
core/didm/llm/judgement.py ``validate_judgement``). The JSON files are generated from
the same enums and field lists so that scorers written outside this repository (the
in-house model's serving code, a prompt's structured-output setting) can use them.
Rules JSON Schema cannot express are listed under ``x-didm-cross-field-rules`` and
are covered by tests/fixtures/didm/conformance/.

Standard library only; no network.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from core.didm.llm import judgement as j
from core.didm.llm import schema as s

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "docs" / "didm" / "schema"
DRAFT = "https://json-schema.org/draft/2020-12/schema"
# The Python validators use fullmatch. A JSON Schema validator searches, and in Python's regex dialect
# "$" also matches just before a final newline, so the exported patterns end with a guard that is
# strict in both dialects (the look-ahead is a no-op in ECMA-262, where "$" is the very end).
_STRICT_END = r"(?!\n)"
ID_PATTERN = s._ID.pattern + _STRICT_END
SHA_PATTERN = s._SHA256.pattern + _STRICT_END
_TOL = f"{j.SUM_TOLERANCE:g}"

_IDENT = {"type": "string", "pattern": ID_PATTERN}
_TIMESTAMP = {"type": "string", "format": "date-time",
              "description": "ISO 8601 with a timezone; a value without one is rejected."}
_SCORE = {"type": "number", "minimum": 0, "maximum": 100}
_PROB = {"type": "number", "minimum": 0, "maximum": 1}
_DIRECTION = {"type": "array", "prefixItems": [_PROB, _PROB, _PROB], "minItems": 3, "maxItems": 3,
              "description": "[P(+1), P(-1), P(0)]"}
_TARGET_RULE = {
    "if": {"properties": {"target_kind": {"const": s.TargetKind.NONE.value}}, "required": ["target_kind"]},
    "then": {"properties": {"entity_id": {"type": "null"}}},
    "else": {"properties": {"entity_id": _IDENT}},
}


def _values(enum) -> list[str]:
    return [e.value for e in enum]


def score_schema() -> dict:
    properties = {
        "record_id": _IDENT,
        "source_id": _IDENT,
        "target_kind": {"enum": _values(s.TargetKind)},
        "entity_id": {"type": ["string", "null"]},
        "published_at": _TIMESTAMP,
        "received_at": _TIMESTAMP,
        "relevance_0_100": _SCORE,
        "ess_like_0_100": _SCORE,
        "novelty_0_100": _SCORE,
        "origin_cluster_id": _IDENT,
        "event_type": {"enum": _values(s.EventType)},
        "direction_probs": _DIRECTION,
        "uncertainty_entropy": {"type": "number"},
        "p_credibility": _PROB,
        "market_confirmation": {"enum": _values(s.MarketConfirmation)},
        "model_version": {"type": "string", "pattern": r"\S"},
        "prompt_sha256": {"type": "string", "pattern": SHA_PATTERN},
        "schema_version": {"const": s.SCHEMA_VERSION},
    }
    missing = [name for name in s.REQUIRED if name not in properties]
    extra = [name for name in properties if name not in s.REQUIRED and name != "schema_version"]
    if missing or extra:
        raise SystemExit(f"export_schema is out of step with schema.REQUIRED: missing {missing}, extra {extra}")
    return {
        "$schema": DRAFT,
        "$id": f"{s.SCHEMA_VERSION}.schema.json",
        "title": s.SCHEMA_VERSION,
        "description": "One DIDM score record: one article judged for one target. Generated by "
                       "tools/didm/export_schema.py from core/didm/llm/schema.py; do not edit by hand.",
        "type": "object",
        "additionalProperties": False,
        "required": list(s.REQUIRED),
        "properties": {name: properties[name] for name in (*s.REQUIRED, "schema_version")},
        "allOf": [_TARGET_RULE],
        "x-didm-cross-field-rules": [
            "direction_probs sums to 1 within 1e-6",
            "P(+1) + P(-1) does not exceed 1 (tolerance 1e-9)",
            "ess_like_0_100 equals 50 + 50*(P(+1) - P(-1)) within 1e-6",
            "uncertainty_entropy equals the Shannon entropy (nats) of direction_probs within 1e-6",
            "published_at and received_at carry a timezone",
        ],
        "x-didm-assembled-by-didm": list(_scorer().ASSEMBLY_FIELDS),
        "x-didm-derived-on-assembly": list(_scorer().DERIVED_FIELDS),
        "x-didm-from-judgement": list(_scorer().JUDGEMENT_TO_RECORD),
        "x-didm-from-scorer-info": list(_scorer().SCORER_INFO_FIELDS),
    }


def judgement_schema() -> dict:
    types = _values(s.EventType)
    properties = {
        "judgement_version": {"const": j.JUDGEMENT_VERSION},
        "article_id": _IDENT,
        "target_kind": {"enum": _values(s.TargetKind)},
        "entity_id": {"type": ["string", "null"]},
        "p_subject": _PROB,
        "event_type": {"enum": types},
        "event_type_probs": {
            "type": "object",
            "additionalProperties": False,
            "required": types,
            "properties": {name: _PROB for name in types},
        },
        "direction_probs": _DIRECTION,
        "claim_status": {"enum": list(j.CLAIM_STATUSES)},
    }
    if tuple(properties) != j.JUDGEMENT_REQUIRED:
        raise SystemExit("export_schema is out of step with judgement.JUDGEMENT_REQUIRED")
    return {
        "$schema": DRAFT,
        "$id": f"{j.JUDGEMENT_VERSION}.schema.json",
        "title": j.JUDGEMENT_VERSION,
        "description": "What a scorer returns for one article and one target. DIDM assembles the "
                       f"{s.SCHEMA_VERSION} record from it. Generated by tools/didm/export_schema.py from "
                       "core/didm/llm/judgement.py; do not edit by hand.",
        "type": "object",
        "additionalProperties": False,
        "required": list(j.JUDGEMENT_REQUIRED),
        "properties": properties,
        "allOf": [_TARGET_RULE],
        "x-didm-cross-field-rules": [
            "article_id, target_kind and entity_id equal the request's",
            "p_subject is 0 when target_kind is none",
            f"event_type_probs sums to 1 within {_TOL}",
            "event_type is a most probable key of event_type_probs (compared exactly; an exact tie leaves a choice)",
            f"direction_probs sums to 1 within {_TOL}",
            "P(+1) + P(-1) does not exceed 1 (tolerance 1e-9)",
        ],
    }


def _scorer():
    from core.didm.llm import scorer
    return scorer


def render(schema: dict) -> str:
    return json.dumps(schema, ensure_ascii=False, indent=2) + "\n"


def targets() -> dict[Path, str]:
    return {
        OUT_DIR / f"{s.SCHEMA_VERSION}.schema.json": render(score_schema()),
        OUT_DIR / f"{j.JUDGEMENT_VERSION}.schema.json": render(judgement_schema()),
    }


def check() -> list[str]:
    problems = []
    for path, text in targets().items():
        rel = path.relative_to(ROOT).as_posix()
        if not path.is_file():
            problems.append(f"{rel}: missing")
            continue
        if path.read_text(encoding="utf-8") != text:
            problems.append(f"{rel}: differs from the code (run python -B -m tools.didm.export_schema)")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare the files with the code; write nothing")
    args = parser.parse_args(argv)
    if args.check:
        problems = check()
        for line in problems:
            print(f"FAIL {line}")
        if not problems:
            print(f"OK {len(targets())} schema files match the code "
                  f"({len(s.EventType)} event types, {len(s.REQUIRED)} required record fields)")
        return 1 if problems else 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in targets().items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
