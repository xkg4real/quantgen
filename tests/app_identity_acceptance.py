"""core.app_identity (OS-P0-c): one place for names and IDs; empty until decided, no secrets, no company suffix."""
from pathlib import Path
import re
import sys
import types
import unittest
from unittest.mock import patch

from core import app_identity

SOURCE = Path(app_identity.__file__).read_text(encoding="utf-8")


class IdentityTests(unittest.TestCase):
    def test_names_match_what_the_desktop_app_already_stores(self):
        app = (Path(app_identity.__file__).resolve().parents[1] / "quantgen_desktop" / "app.py").read_text(encoding="utf-8")
        self.assertIn(f'QSettings("{app_identity.ORGANIZATION_NAME}", "{app_identity.APPLICATION_NAME}")', app)
        branding = (Path(app_identity.__file__).resolve().parents[1] / "quantgen_desktop" / "windows_branding.py").read_text(encoding="utf-8")
        self.assertIn(f'APP_ID = "{app_identity.WINDOWS_APP_USER_MODEL_ID}"', branding)

    def test_no_company_suffix_before_incorporation(self):
        for name in ("SERVICE_NAME", "ORGANIZATION_NAME", "APPLICATION_NAME", "PUBLISHER_DISPLAY_NAME"):
            value = getattr(app_identity, name)
            with self.subTest(name=name):
                self.assertNotRegex(value, r"\(주\)|㈜|주식회사|Inc\.|Corp|Co\., Ltd|LLC")

    def test_undecided_values_are_empty_and_unconfigured(self):
        for name in ("UPDATE_FEED_URL", "COGNITO_REGION", "COGNITO_USER_POOL_ID", "COGNITO_DESKTOP_CLIENT_ID",
                     "LICENSE_PUBLIC_KEY_PEM"):
            with self.subTest(name=name):
                self.assertEqual(getattr(app_identity, name), "")
        self.assertFalse(app_identity.accounts_configured())
        self.assertFalse(app_identity.BUNDLE_ID_CONFIRMED)
        self.assertRegex(app_identity.BUNDLE_ID, r"^[a-z0-9]+(\.[a-z0-9]+){2,}$")

    def test_no_secret_in_the_identity_file(self):
        self.assertIsNone(re.search(r"(?i)(secret|password|token|PRIVATE KEY)\s*=", SOURCE))

    def test_gateway_starts_personal_with_the_company_server_off(self):
        # D7-G (owner approval 2026-11-18): today every source runs on this PC; the company route stays off.
        self.assertEqual(app_identity.GATEWAY_PROFILE, "personal")
        self.assertIn(app_identity.GATEWAY_PROFILE, app_identity.GATEWAY_PROFILES)
        self.assertEqual(app_identity.DATA_API_BASE, "")
        self.assertFalse(app_identity.company_data_server_configured())

    def test_source_checkout_is_a_dev_build_and_a_public_build_never_reads_dotenv(self):
        self.assertEqual(app_identity.build_channel(), "dev")
        self.assertTrue(app_identity.may_read_dotenv())
        root = Path(app_identity.__file__).resolve().parent
        self.assertFalse((root / "_build_info.py").exists(), "the build channel file is generated by packaging only")
        for channel, expected in (("public", "public"), ("beta", "beta"), ("bogus", "dev")):
            with self.subTest(channel=channel), patch.dict(sys.modules, {"core._build_info": types.SimpleNamespace(CHANNEL=channel)}):
                self.assertEqual(app_identity.build_channel(), expected)


if __name__ == "__main__":
    unittest.main()
