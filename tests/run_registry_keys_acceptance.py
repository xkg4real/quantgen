def decode_tags(value):
    if isinstance(value, list):
        return [decode_tags(item) for item in value]
    if isinstance(value, dict):
        if set(value) == {"__date__"}:
            return date.fromisoformat(value["__date__"])
        if set(value) == {"__tuple__"}:
            return tuple(decode_tags(item) for item in value["__tuple__"])
        return {key: decode_tags(item) for key, item in value.items()}
    return value


def fixture():
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def planned(case):
    return lab_config_ids(case["rule"], case["is_pairs"], case["symbols"],
                          decode_tags(case["grid"]), case["cost_bps"])


def expected_entries(records):
    return [{"theta_index": entry["theta_index"], "config_id": entry["config_id"]}
            for entry in records]


@contextmanager
def current_writer():
    """Real current registrar, guarded before imports, with no default path.

    The process-local audit hook is active only inside this context; it cannot
    authorize other roots. dotenv is disabled before any workflow/config import.
    Only git-anchor metadata is fixed; writer and ledger code are unmodified.
    """
    active = {"root": None}
    accesses = []

    def guard(event, args):
        root = active["root"]
        if root is None:
            return
        if event in ("socket.connect", "socket.getaddrinfo"):
            raise AssertionError("provider/network operation forbidden")
        if event == "open" and isinstance(args[0], (str, bytes, os.PathLike)):
            path = Path(os.fsdecode(args[0]))
            parts = path.parts
            if any(part.startswith(".env") or part in
                   ("holdout", "frozen", "paper_live", "grokteam", "cards",
                    ".nextgen", "_backup") for part in parts):
                raise AssertionError("protected payload forbidden")
            if "asset_expansion" in parts and "cache" in parts:
                raise AssertionError("protected cache forbidden")
            if path.suffix in (".jsonl", ".lock"):
                resolved = path.resolve()
                if not resolved.is_relative_to(root):
                    raise AssertionError("non-temporary ledger/lock forbidden")
                accesses.append(resolved)

    sys.addaudithook(guard)
    with tempfile.TemporaryDirectory(prefix="qg-key-writer-") as directory:
        root = Path(directory).resolve()
        if not root.is_relative_to(Path(tempfile.gettempdir()).resolve()):
            raise AssertionError("temporary root required")
        active["root"] = root
        try:
            import dotenv
            with patch.object(dotenv, "load_dotenv", return_value=False):
                workflow = importlib.import_module("core.research.strategy_workflow")
                ledger = importlib.import_module("core.quant.gate_ledger")
                config = importlib.import_module("config")
                with patch.object(config, "macro_dir", side_effect=AssertionError("default path forbidden")), \
                        patch.object(ledger, "repo_anchor", return_value="git:" + "1" * 40):
                    yield workflow, ledger, root, accesses
        finally:
            active["root"] = None


class RunRegistryKeysTests(unittest.TestCase):
    def test_historical_literal_ids_and_nine_field_canonical_bytes(self):
        data = fixture()
        self.assertEqual(data["provenance"]["historical_ref"], HISTORICAL_REF)
        self.assertEqual(data["provenance"]["writer_function_sha256"], WRITER_SHA256)
        families = set()
        for case in data["cases"]:
            if "SYNTHETIC" in case["sources"]:
                continue
            with self.subTest(case=case["name"]):
                families.add(case["family"])
                self.assertEqual(case["rule"], FAMILY_IDS[case["family"]])
                self.assertEqual(planned(case), expected_entries(case["expected"]))
                for entry in case["expected"]:
                    raw = entry["canonical_key_json"].encode("utf-8")
                    self.assertFalse(raw.endswith(b"\n"))
                    self.assertEqual(hashlib.md5(raw, usedforsecurity=False).hexdigest(), entry["config_id"])
                    row = json.loads(raw)
                    self.assertEqual(set(row), {"rule", "params", "estimator", "window", "cap",
                                                "instrument_book", "rebalance", "timing_class", "start_convention"})
                    self.assertEqual(row["timing_class"], "COMPLIANT")
                    for name in ("estimator", "window", "cap", "instrument_book", "rebalance", "start_convention"):
                        self.assertIsNone(row[name])
        self.assertEqual(families, set(FAMILY_IDS))

    def test_writer_function_exact_bytes_pinned_after_relocation(self):
        raw = (ROOT / "core" / "research" / "strategy_workflow.py").read_bytes()
        tree = ast.parse(raw.decode("utf-8"))
        node = next(item for item in tree.body if isinstance(item, ast.FunctionDef)
                    and item.name == "register_trials")
        source = b"".join(raw.splitlines(keepends=True)[node.lineno - 1:node.end_lineno])
        self.assertEqual(len(source), 1708)
        self.assertEqual(hashlib.sha256(source).hexdigest(), WRITER_SHA256)

    def test_symbols_pairs_duplicates_and_positional_grid_entries(self):
        grid = [{"lookback": 126}, {"lookback": 126}]
        keys = lab_config_ids("E1", False, [" spy ", "qqq"], grid, 50)
        self.assertEqual(keys, lab_config_ids("E1", False, ["QQQ", "SPY"], grid, 50))
        self.assertEqual([entry["theta_index"] for entry in keys], [0, 1])
        self.assertEqual(keys[0]["config_id"], keys[1]["config_id"])
        self.assertNotEqual(keys, lab_config_ids("E1", False, ["QQQ", "SPY", "SPY"], grid, 50))
        self.assertNotEqual(lab_config_ids("E8", True, ["SPY", "QQQ"], grid, 50),
                            lab_config_ids("E8", True, ["QQQ", "SPY"], grid, 50))

    def test_numeric_types_and_roundtrip_are_not_normalized(self):
        grid = [{"lookback": 126}]
        self.assertNotEqual(lab_config_ids("E1", False, ["SPY"], grid, 50),
                            lab_config_ids("E1", False, ["SPY"], grid, 50.0))
        self.assertNotEqual(lab_config_ids("E1", False, ["SPY"], grid, 50),
                            lab_config_ids("E1", False, ["SPY"], [{"lookback": 126.0}], 50))
        first = [{"x": (1, 2), "date": date(2026, 11, 6), "nested": {2: "둘", 1: "하나"}}]
        second = [{"nested": {"1": "하나", "2": "둘"}, "date": "2026-11-06", "x": [1, 2]}]
        self.assertEqual(lab_config_ids("E1", False, ["SPY"], first, 50),
                         lab_config_ids("E1", False, ["SPY"], second, 50))

    def test_resolved_us_table_literal_and_typed_cost_keep_exact_key_types(self):
        # Source-only provenance for an already resolved cost input. This neither
        # executes the cost resolver nor establishes venue/data/eligibility facts.
        tree = ast.parse((ROOT / "core" / "quant" / "validate.py").read_text(encoding="utf-8"))
        node = next(item for item in tree.body if isinstance(item, ast.Assign)
                    and any(isinstance(target, ast.Name) and target.id == "COST_BP_PER_SIDE"
                            for target in item.targets))
        table_literal = ast.literal_eval(node.value)["us"]
        self.assertIs(type(table_literal), float)
        self.assertEqual(table_literal, 50.0)
        case = next(item for item in fixture()["cases"]
                    if item["name"] == "trend_switch_all_grid_cost_float")
        self.assertEqual(lab_config_ids(case["rule"], case["is_pairs"], case["symbols"],
                                      decode_tags(case["grid"]), table_literal), planned(case))
        self.assertEqual(planned(case), expected_entries(case["expected"]))
        self.assertNotEqual(lab_config_ids(case["rule"], case["is_pairs"], case["symbols"],
                                         decode_tags(case["grid"]), 50), planned(case))

    def test_explicit_symbols_cost_override_theta_and_inputs_stay_unchanged(self):
        symbols = [" spy ", "qqq"]
        grid = [{"symbols": ["discarded"], "cost_bps": 999, "nested": {"x": [1, 2]},
                 "when": date(2026, 11, 6), "estimator": "nested parameter"}]
        before = copy.deepcopy((symbols, grid))
        key = lab_config_ids("E1", False, symbols, grid, 50)
        other = copy.deepcopy(grid)
        other[0]["symbols"] = []
        other[0]["cost_bps"] = -1
        self.assertEqual(key, lab_config_ids("E1", False, symbols, other, 50))
        self.assertEqual((symbols, grid), before)
        self.assertEqual(lab_config_ids("E1", False, [], [], 0), [])

    def test_nonfinite_cycle_encoding_failures_and_bad_shapes_refused(self):
        for cost in (None, "50", True, float("nan"), float("inf"), -float("inf")):
            with self.subTest(cost=cost), self.assertRaises(KeyBuildError):
                lab_config_ids("E1", False, ["SPY"], [], cost)
        for value in (float("nan"), float("inf"), -float("inf"), "\ud800", 10 ** 5000):
            with self.subTest(value_type=type(value).__name__), self.assertRaises(KeyBuildError):
                lab_config_ids("E1", False, ["SPY"], [{"value": value}], 50)
        cycle = {}
        cycle["self"] = cycle
        with self.assertRaises(KeyBuildError):
            lab_config_ids("E1", False, ["SPY"], [cycle], 50)
        for args in [("", False, [], [], 50), ("E1", 1, [], [], 50),
                     ("E1", False, "SPY", [], 50), ("E1", False, [1], [], 50),
                     ("E1", False, [], {}, 50), ("E1", False, [], [1], 50)]:
            with self.subTest(args=args), self.assertRaises(KeyBuildError):
                lab_config_ids(*args)

    def test_helper_needs_no_files_network_or_other_product_modules(self):
        with patch("builtins.open", side_effect=AssertionError("file I/O forbidden")), \
                patch.object(socket.socket, "connect", side_effect=AssertionError("network forbidden")):
            self.assertEqual(len(lab_config_ids("CALLER_RULE", False, ["TEST"], [{}], 0)), 1)
        tree = ast.parse((ROOT / "core" / "quant" / "run_registry_keys.py").read_text())
        imports = [node.module for node in ast.walk(tree) if isinstance(node, ast.ImportFrom)]
        imports += [alias.name for node in ast.walk(tree) if isinstance(node, ast.Import) for alias in node.names]
        self.assertEqual(set(imports), {"__future__", "collections.abc", "hashlib", "json"})

    def test_actual_current_writer_matches_historical_cases_in_temporary_ledgers(self):
        with current_writer() as (workflow, ledger, root, accesses):
            self.assertEqual(workflow.FAMILY_ID, FAMILY_IDS)
            for index, case in enumerate(fixture()["cases"]):
                if "SYNTHETIC" in case["sources"]:
                    continue
                with self.subTest(case=case["name"]):
                    directory = root / str(index)
                    count = workflow.register_trials(case["family"], case["symbols"],
                        decode_tags(case["grid"]), case["cost_bps"],
                        ["2020-01-02", "2020-12-31"], case["sources"], ledger_dir=directory)
                    rows = ledger.family_ledger(case["rule"], directory).rows()
                    unique = list(dict.fromkeys(entry["config_id"] for entry in case["expected"]))
                    self.assertEqual([row["config_id"] for row in rows], unique)
                    self.assertEqual(count, len(unique))
                    self.assertEqual(list(dict.fromkeys(entry["config_id"] for entry in planned(case))), unique)
            self.assertTrue(accesses)
            self.assertTrue(all(path.is_relative_to(root) for path in accesses))

    def test_current_full_family_grids_match_pinned_historical_grid_cases(self):
        with current_writer() as (workflow, _ledger, _root, _accesses):
            for family in FAMILY_IDS:
                # Historical generator marks complete original family-grid cases.
                cases = [case for case in fixture()["cases"] if case["family"] == family
                         and case.get("full_family_grid")]
                self.assertEqual({type(case["cost_bps"]) for case in cases}, {int, float})
                for case in cases:
                    self.assertEqual(workflow.FAMILIES[family][2], decode_tags(case["grid"]))

    def test_synthetic_source_skips_registration_while_planned_keys_remain(self):
        with current_writer() as (workflow, _ledger, root, accesses):
            case = next(case for case in fixture()["cases"] if "SYNTHETIC" in case["sources"])
            grid = decode_tags(case["grid"])
            # Omitting ledger_dir here is deliberate: SYNTHETIC must return before
            # the patched default-path function, imports or any ledger creation.
            result = workflow.register_trials(case["family"], case["symbols"], grid,
                        case["cost_bps"], ["2020-01-02", "2020-12-31"], case["sources"])
            self.assertIsNone(result)
            self.assertEqual(case["expected"], [])
            reference = next(item for item in fixture()["cases"]
                             if item["name"] == case["expected_planned_reference"])
            self.assertEqual(planned(case), expected_entries(reference["expected"]))
            self.assertTrue(planned(case))
            self.assertEqual(list(root.iterdir()), [])
            self.assertEqual(accesses, [])

    def test_actual_writer_requires_explicit_temporary_path_in_this_fixture(self):
        with current_writer() as (workflow, _ledger, root, accesses):
            with self.assertRaisesRegex(AssertionError, "default path forbidden"):
                workflow.register_trials("trend_switch", ["SPY"], [{}], 50,
                    ["2020-01-02", "2020-12-31"], ["FIXTURE"])
            self.assertEqual(list(root.iterdir()), [])
            self.assertEqual(accesses, [])

    def test_unhashed_metadata_changes_dedup_in_current_temporary_writer(self):
        with current_writer() as (workflow, ledger, root, _accesses):
            first = workflow.register_trials("trend_switch", ["SPY"], [{"lookback": 126}], 50,
                        ["2020-01-02", "2020-12-31"], ["FIXTURE_A"], ledger_dir=root)
            second = workflow.register_trials("trend_switch", ["SPY"], [{"lookback": 126}], 50,
                        ["2021-01-02", "2021-12-31"], ["FIXTURE_B"], ledger_dir=root)
            self.assertEqual((first, second), (1, 1))
            rows = ledger.family_ledger("E1", root).rows()
            self.assertEqual([row["config_id"] for row in rows],
                             [entry["config_id"] for entry in lab_config_ids("E1", False, ["SPY"], [{"lookback": 126}], 50)])


